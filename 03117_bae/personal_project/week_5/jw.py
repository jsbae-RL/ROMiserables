def solution(answers):
    math_patterns = [
        [1, 2, 3, 4, 5, 1],        # 1번 수포자 패턴
        [2, 1, 2, 3, 2, 4, 2, 5],  # 2번 수포자 패턴
        [3, 3, 1, 1, 2, 2, 4, 4, 5, 5]  # 3번 수포자 패턴
    ]
    
    scores = [0, 0, 0]  # 각 수포자의 점수

    # 정답을 하나씩 확인하면서 점수 계산
    for i, answer in enumerate(answers):
        for j, pattern in enumerate(math_patterns):
            if answer == pattern[i % len(pattern)]:  # 패턴이 반복되도록
                scores[j] += 1

    # 최고 점수 찾기
    max_score = max(scores)

    # 최고 점수를 받은 사람 찾기 (오름차순 자동 유지)
    return [i + 1 for i, score in enumerate(scores) if score == max_score]


